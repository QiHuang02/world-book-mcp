export function getToolUsageGuide(tool: string): ToolUsageGuide | { available_tools: string[]; message: string } {
  return GUIDES[tool] ?? {
    message: `未找到 ${tool} 的专门指南，可先调用 get_worldbook_workflow 获取总体流程。`,
    available_tools: Object.keys(GUIDES).sort(),
  };
}
